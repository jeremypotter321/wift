// Screenshot every WIFT screen from the built app (window stays hidden). Usage: node scripts/shoot.mjs <outDir> <dataDir>
import { _electron as electron } from 'playwright'
const [out, dataDir] = process.argv.slice(2)
const app = await electron.launch({ args: ['.'], env: { ...process.env, SHOPBOARD_DATA_DIR: dataDir, SHOPBOARD_SEED: '1', SHOPBOARD_HIDDEN: '1' } })
const page = await app.firstWindow()
const errors = []
page.on('pageerror', (e) => errors.push(String(e)))
page.on('console', (m) => m.type() === 'error' && errors.push(m.text()))
await page.setViewportSize({ width: 1360, height: 860 })
await page.waitForSelector('.kpi', { timeout: 20000 })
const shot = async (name) => { await page.waitForTimeout(300); await page.screenshot({ path: `${out}/${name}.png` }) }
const nav = (label) => page.click(`.sb-item:has-text("${label}")`)
const checks = {}
await shot('01-dashboard')
await nav('Job board'); await shot('02-board')
await page.click('.col:has-text("Work in progress") .rcard:has-text("Priya")'); await shot('03-ro-jobs')
checks.verdictShown = await page.locator('.verdict-line, .verdict').count()
await page.click('[role=tab]:has-text("Inspection")'); await shot('04-ro-inspection')
await page.click('.dvi-row:has-text("Electric water pump") button[aria-expanded]'); await shot('05-ro-inspection-open')
await page.click('[role=tab]:has-text("Notes")'); await shot('06-ro-notes')
await nav('Job board'); await page.click('.col:has-text("Estimates") .rcard:has-text("Tom Becker")'); await shot('07-ro-estimate')
await page.click('button:has-text("Get signature")'); await page.waitForTimeout(200)
const c = await page.locator('.sigpad canvas').boundingBox()
await page.mouse.move(c.x + 40, c.y + 120); await page.mouse.down()
for (let i = 0; i < 20; i++) await page.mouse.move(c.x + 40 + i * 14, c.y + 120 - Math.sin(i / 2) * 30)
await page.mouse.up(); await shot('08-signature')
await page.click('button:has-text("Approve and sign")'); await page.waitForTimeout(400)
checks.afterSignStatus = await page.locator('.ro-header .pill').first().innerText()
await page.click('button:has-text("Print estimate")'); await page.waitForTimeout(500); await shot('09-print'); await page.keyboard.press('Escape')
await page.click('button:has-text("Add canned job")'); await page.fill('.modal input', 'injector'); await shot('10-canned-picker'); await page.keyboard.press('Enter'); await page.waitForTimeout(300)
checks.jobsAfterCanned = await page.locator('.job').count()
await shot('11-ro-after-canned')
await nav('Appointments'); await shot('12-appointments')
await nav('Time clock'); await shot('13-timeclock')
await nav('Customers'); await shot('14-customers')
await page.click('td:has-text("Dale Hendricks")'); await shot('15-customer')
await page.click('td:has-text("335i")'); await shot('16-vehicle')
await nav('Reminders'); await page.selectOption('select[aria-label=Window]', 'all'); await shot('17-reminders')
await nav('Inventory'); await shot('18-inventory')
await nav('Purchase orders'); await shot('19-pos')
await page.click('td:has-text("PO 1")'); await shot('20-po')
await nav('Vendors'); await shot('21-vendors')
await nav('Payments'); await shot('22-ar')
await nav('Reports'); await shot('23-reports')
await page.click('.sec-link:has-text("Sales")'); await page.click('button[role=radio]:has-text("Last 30 days")'); await shot('24-report-sales')
await nav('Accountant export'); await shot('25-export')
await nav('Canned jobs'); await page.click('.menu-item:has-text("N54 turbos")'); await shot('26-canned')
await nav('Settings'); await page.click('.sec-link:has-text("Pricing matrix")'); await shot('27-settings-matrix')
await page.click('.sec-link:has-text("Users")'); await shot('28-settings-users')
await page.keyboard.press('Meta+k'); await page.keyboard.type('PRS'); await shot('29-search')
await page.keyboard.press('Enter'); await page.waitForTimeout(200); checks.searchLanded = await page.locator('h1').first().innerText()
// Tech role: no prices
await page.click('.user-chip'); await page.click('.modal button:has-text("Luis")'); await page.waitForTimeout(200)
await nav('Job board'); await page.click('.rcard:has-text("Priya")'); await shot('30-ro-as-tech')
checks.techSeesTotals = await page.locator('.shop-only, .totals').count()
console.log(JSON.stringify({ checks, errors }, null, 1))
await app.close()
