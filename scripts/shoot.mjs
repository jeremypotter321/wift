// Screenshot every screen from the built app (window stays hidden). Usage: node scripts/shoot.mjs <outDir> <dataDir>
import { _electron as electron } from 'playwright'
const [out, dataDir] = process.argv.slice(2)
const app = await electron.launch({ args: ['.'], env: { ...process.env, SHOPBOARD_DATA_DIR: dataDir, SHOPBOARD_SEED: '1', SHOPBOARD_HIDDEN: '1' } })
const page = await app.firstWindow()
const errors = []
page.on('pageerror', (e) => errors.push(String(e)))
page.on('console', (m) => m.type() === 'error' && errors.push(m.text()))
await page.setViewportSize({ width: 1280, height: 820 })
await page.waitForSelector('.kpi')
const shot = async (name) => { await page.waitForTimeout(250); await page.screenshot({ path: `${out}/${name}.png` }) }
await shot('01-dashboard')
await page.click('.nav-item:has-text("Jobs")'); await shot('02-jobs')
await page.click('td:has-text("1972 C10 frame-off restoration")'); await shot('03-job-overview')
const custBefore = await page.inputValue('input[list=customer-list]')
await page.selectOption('select[aria-label=Status]', 'Waiting on parts'); await page.waitForTimeout(300)
await page.selectOption('select[aria-label=Status]', 'In progress'); await page.waitForTimeout(300)
const custAfter = await page.inputValue('input[list=customer-list]')
await page.click('[role=tab]:has-text("Labor")'); await shot('04-job-labor')
await page.click('button:has-text("▶ Start")'); await page.waitForTimeout(1500); await shot('05-job-labor-timer')
await page.click('button:has-text("■ Stop")')
await page.click('[role=tab]:has-text("Parts")'); await shot('06-job-parts')
await page.click('[role=tab]:has-text("Content")'); await shot('07-job-content')
await page.click('.nav-item:has-text("Should I take it?")'); await shot('08-new-empty')
await page.fill('input[placeholder="Name"]', 'Jess Park')
await page.fill('input[placeholder="e.g. Front brakes + rotors"]', 'Rebuild 5.3 heads')
await page.locator('label.field:has-text("Quoted labor price") input').fill('1100')
await page.locator('label.field:has-text("Estimated hours") input').fill('9')
await page.locator('label.field:has-text("Estimated parts cost") input').fill('600')
await page.check('label.check:has-text("Rust") input')
await shot('09-new-verdict')
const verdictWord = await page.locator('.verdict .word').innerText()
await page.click('.nav-item:has-text("Export")'); await page.click('button:has-text("All time")'); await shot('10-export')
await page.click('.nav-item:has-text("Settings")'); await shot('11-settings')
console.log(JSON.stringify({ verdictWord, custBefore, custAfter, errors }))
await app.close()
